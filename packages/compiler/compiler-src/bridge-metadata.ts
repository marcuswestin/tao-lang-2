type BridgeContract = {
  arity?: string
  exportName: string
  path: string
  result?: string
  sourceRange?: DiagnosticRange
  type: string
}

export type BridgeSourceMapping = { generated: DiagnosticRange; source: DiagnosticRange }
export type BridgeGeneratedModule = {
  path: string
  code: string
  sourcePath: string
  sourceMappings: readonly BridgeSourceMapping[]
}
export type BridgeModule = BridgeGeneratedModule & {
  implementationPaths: readonly { sourcePath: string; path: string }[]
  quantityModule?: BridgeGeneratedModule
}

let quantityTypeBindings: ReadonlyMap<AST.TypeDeclaration, string> = new Map()

export type QuantityPublicationDeclaration = QuantityNativeSurface['byDeclaration'] extends ReadonlyMap<
  AST.TypeDeclaration,
  infer Row
> ? Readonly<Row & { declaration: AST.TypeDeclaration; owner: AST.TypeDeclaration }>
  : never
export type QuantityPublicationSurface = Readonly<{
  namespaceExport: string
  facadeNamespaceExport: string
  declarations: readonly QuantityPublicationDeclaration[]
  typeExportsByName: ReadonlyMap<string, string>
}>
export type QuantityCanonicalLeaf = Pick<QuantityNativeModuleOutput, 'path' | 'namespaceExport' | 'linkageByOwner'>
export type QuantityCanonicalLeaves = ReadonlyMap<AST.TypeDeclaration, QuantityCanonicalLeaf>
export type QuantityPublicationModule = QuantityNativeModuleOutput & { surface: QuantityPublicationSurface }

export const bridgeGeneratedMarker =
  '// Generated by Tao. Edit the .tao source or its handwritten TypeScript sidecar instead.'

/** BridgeMetadata is the TypeScript-facing contract generated beside each Tao boundary source. */
export const BridgeMetadata = {
  resultType: typescriptType,
  quantityModuleFor,
  quantitySurfaceFor,
  quantityReferencedOwnersOf,
  withQuantityTypeBindings<Result>(bindings: ReadonlyMap<AST.TypeDeclaration, string>, emit: () => Result): Result {
    const previous = quantityTypeBindings
    quantityTypeBindings = bindings
    try {
      return emit()
    } finally {
      quantityTypeBindings = previous
    }
  },
  quantityExportsFor,
  /** Expected result of a native expression at its explicitly typed Tao boundary. */
  bridgeResultType: bridgedResultType,
  /** Source sidecar roots referenced by a reachable declaration closure, without sibling declarations. */
  implementationSidecarRoots(declarations: readonly AST.Declaration[]): readonly string[] {
    const roots = new Set<string>()
    const add = (node: AST.Node, path: string): void => {
      roots.add(FS.resolvePath(path, FS.dirname(AST.getDocument(node).uri.path)))
    }
    for (const declaration of declarations) {
      for (const node of [declaration, ...AST.streamAllContents(declaration)]) {
        if (AST.isFromExpression(node)) {
          add(node, node.path)
        } else if (AST.isActionDeclaration(node) && node.foreign !== undefined) {
          add(node, node.foreign.path)
        } else if (AST.isViewDeclaration(node) && node.foreign !== undefined) {
          add(node, node.foreign.path)
        }
      }
      if (AST.isConfigurableDeclaration(declaration)) {
        const implementation = directConfigurationImplementation(declaration)
        if (implementation !== undefined) {
          add(implementation, implementation.path)
        }
      }
    }
    return [...roots]
  },
  /** typesFor mirrors the exported contract types in compiled Tao modules for copied sidecars. */
  typesFor(file: AST.TaoFile, statements: readonly AST.Statement[] = file.statements): string {
    const contracts = contractsOf(file, statements)
    return contracts.map((contract, index) => `export type ${contractTypeName(contracts, index)} = ${contract.type}`)
      .join('\n')
  },

  /** Case identities remain available to TypeScript type queries without selecting runtime work. */
  caseSetTypesFor(statements: readonly AST.Statement[]): string {
    return statements.filter(AST.isTypeDeclaration).filter(declaration => AST.isCaseSetTypeExpression(declaration.type))
      .map(caseSetTypeDeclaration).join('\n')
  },

  /** collect plans contracts without writing files; the project service owns publication. */
  collect(
    files: readonly ParsedFile[],
    projectRoot: string,
    origins: ReadonlyMap<string, ModuleOrigin> = new Map(),
    options: {
      runtimeRoot?: string
      selectedStatementsBySourcePath?: ReadonlyMap<string, readonly AST.Statement[]>
    } = {},
  ): BridgeModule[] {
    const canonicalLeaves = new Map<AST.TypeDeclaration, QuantityCanonicalLeaf>()
    const surfaces = new Map<string, QuantityPublicationSurface>()
    for (const file of files) {
      const surface = quantitySurfaceFor(file.ast)
      if (surface === undefined) {
        continue
      }
      surfaces.set(file.path, surface)
      const companionPath = bridgeOutputPath(projectRoot, file.path, origins.get(file.path))
      const outputPath = `${companionPath.replace(/\.ts$/, '')}.quantities.ts`
      const directRows = surface.declarations.filter(row => row.declaration === row.owner)
      if (directRows.length > 0) {
        const planned = QuantityNativeModule.planSurface({
          declarations: surface.declarations.map(row => row.declaration),
          parentsByDeclaration: new Map(
            surface.declarations.flatMap(row =>
              row.parent === undefined ? [] : [[row.declaration, row.parent] as const]
            ),
          ),
          reservedNames: quantityReservedNames(file.ast),
        })
        for (const row of directRows) {
          const names = planned.byDeclaration.get(row.owner)
          Assert.defined(names, 'canonical quantity declaration has preplanned linkage names')
          const previous = canonicalLeaves.get(row.owner)
          Assert(previous === undefined, 'canonical quantity owner has one publication leaf')
          canonicalLeaves.set(row.owner, {
            path: outputPath,
            namespaceExport: planned.namespaceExport,
            linkageByOwner: new Map([[row.owner, {
              owner: row.owner,
              constructorMember: names.constructorMember,
              typeMember: names.typeMember,
              valueTypeExport: names.valueTypeExport,
              factoryExport: names.factoryExport,
            }]]),
          })
        }
      }
    }
    const leaves = new Map(files.flatMap(file => {
      const companionPath = bridgeOutputPath(projectRoot, file.path, origins.get(file.path))
      const leaf = quantityModuleFor(
        file.ast,
        `${companionPath.replace(/\.ts$/, '')}.quantities.ts`,
        quantityRuntimeRoot(options.runtimeRoot),
        canonicalLeaves,
        surfaces.get(file.path),
      )
      return leaf === undefined ? [] : [[file.path, leaf] as const]
    }))
    return files.flatMap(file => {
      const selected = options.selectedStatementsBySourcePath?.get(file.path)
      const statements = selected === undefined ? file.ast.statements : selected.map(statement => {
        const current = [file.ast, ...AST.streamAllContents(file.ast)].filter(AST.isStatement).filter(candidate =>
          candidate.$type === statement.$type && candidate.$cstNode?.offset === statement.$cstNode?.offset
        )
        Assert(current.length === 1, 'selected publication statement has one validated source identity')
        return current[0]!
      })
      const path = bridgeOutputPath(projectRoot, file.path, origins.get(file.path))
      const bindings = new Map(
        [...new Set(canonicalLeaves.values())].flatMap(leaf =>
          [...leaf.linkageByOwner].map(([owner, link]) =>
            [owner, `import(${JSON.stringify(relativeModulePath(path, leaf.path))}).${link.valueTypeExport}`] as const
          )
        ),
      )
      for (const owner of quantityReferencedOwnersOf(file.ast)) {
        const { leaf, link } = canonicalQuantityLink(owner, canonicalLeaves)
        bindings.set(owner, `import(${JSON.stringify(relativeModulePath(path, leaf.path))}).${link.valueTypeExport}`)
      }
      return BridgeMetadata.withQuantityTypeBindings(bindings, () => {
        const contracts = contractsOf(file.ast, statements)
        const quantityModule = leaves.get(file.path)
        if (
          contracts.length === 0
          && quantityModule === undefined
          && !file.ast.statements.some(isRuntimeConfigurableDeclaration)
          && !file.ast.statements.some(statement =>
            AST.isTypeDeclaration(statement) && AST.isCaseSetTypeExpression(statement.type)
          )
        ) {
          return []
        }
        const origin = origins.get(file.path)
        const implementationPaths = [...new Set(contracts.map(contract => contract.path))].map(contractPath => {
          const sourcePath = FS.resolvePath(contractPath, FS.dirname(file.path))
          return {
            sourcePath,
            path: isForeignOrigin(origin, projectRoot)
              ? dependencySnapshotPath(projectRoot, sourcePath, origin)
              : sourcePath,
          }
        })
        return [{
          path,
          ...moduleFor(
            contracts,
            file.ast.statements,
            path,
            file.path,
            implementationPaths,
            options.runtimeRoot,
            quantityModule,
            file.ast,
          ),
          sourcePath: file.path,
          implementationPaths,
          ...(quantityModule === undefined ? {} : { quantityModule: { ...quantityModule, sourcePath: file.path } }),
        }]
      })
    })
  },
  dependencyNamespace,
  dependencySnapshotPath,
} as const

function quantityRuntimeRoot(runtimeRoot?: string): string {
  return runtimeRoot ?? FS.dirname(FS.dirname(
    TaoResources.resolve(`${TaoResources.RUNTIME_DIRECTORY}/TaoRuntime-src/TR.ts`)
      ?? FS.resolvePath('../../apps/runtime/TaoRuntime-src/TR.ts', import.meta.dirname),
  ))
}

function quantityModuleFor(
  file: AST.TaoFile,
  outputPath: string,
  runtimeRoot: QuantityNativeModuleOptions['runtimeRoot'],
  canonicalLeaves: QuantityCanonicalLeaves = new Map(),
  plannedSurface?: QuantityPublicationSurface,
): QuantityPublicationModule | undefined {
  const surface = plannedSurface ?? quantitySurfaceFor(file)
  if (surface === undefined) {
    return undefined
  }
  const direct = directQuantityModuleFor(file, outputPath, runtimeRoot, surface, canonicalLeaves)
  const lines = direct?.code.trimEnd().split('\n') ?? [bridgeGeneratedMarker]
  const mappings = [...direct?.sourceMappings ?? []]
  const links = new Map(direct?.linkageByOwner)
  for (const row of surface.declarations.filter(row => row.declaration !== row.owner)) {
    const own = direct?.linkageByOwner.get(row.owner)
    const canonical = own === undefined
      ? canonicalQuantityLink(row.owner, canonicalLeaves)
      : { leaf: direct!, link: own }
    const source = row.declaration.$cstNode?.range
    Assert.defined(source, 'quantity forwarding declaration has a source range')
    const append = (line: string): void => {
      mappings.push({
        generated: {
          start: { line: lines.length, character: 0 },
          end: { line: lines.length, character: line.length },
        },
        source,
      })
      lines.push(line)
    }
    let valueType: string
    let constructors: string
    if (canonical.leaf.path === outputPath) {
      const canonicalRow: QuantityPublicationDeclaration | undefined = surface.declarations.find(candidate =>
        candidate.declaration === canonical.link.owner
      )
      Assert.defined(canonicalRow, 'same-leaf forwarding has its canonical declaration surface')
      valueType = canonical.link.valueTypeExport
      constructors = `${surface.namespaceExport}.${canonical.link.constructorMember}`
      append(`export type ${row.valueTypeExport} = ${valueType}`)
      append(`export { ${canonicalRow.factoryLocal} as ${row.factoryExport} }`)
    } else {
      const specifier = JSON.stringify(relativeModulePath(outputPath, canonical.leaf.path))
      valueType = `import(${specifier}).${canonical.link.valueTypeExport}`
      constructors = `${row.constructorImport}.${canonical.link.constructorMember}`
      append(`import { ${canonical.leaf.namespaceExport} as ${row.constructorImport} } from ${specifier}`)
      append(`export type { ${canonical.link.valueTypeExport} as ${row.valueTypeExport} } from ${specifier}`)
      append(`export { ${canonical.link.factoryExport} as ${row.factoryExport} } from ${specifier}`)
    }
    append(`export namespace ${surface.namespaceExport} {`)
    append(`  export type ${row.typeMember} = ${valueType}`)
    append(
      canonical.leaf.path === outputPath
        ? `  export const ${row.constructorMember} = ${constructors}`
        : `  export const ${row.constructorMember}: typeof ${constructors} = void 0 as never`,
    )
    append('}')
    if (canonical.leaf.path !== outputPath) {
      append(`Object.defineProperty(${surface.namespaceExport}, ${JSON.stringify(row.constructorMember)}, {`)
      append('  enumerable: true, configurable: true,')
      append(`  get: () => ${constructors},`)
      append('})')
    }
    if (!links.has(row.owner)) {
      links.set(row.owner, {
        owner: row.owner,
        constructorMember: row.constructorMember,
        typeMember: row.typeMember,
        valueTypeExport: row.valueTypeExport,
        factoryExport: row.factoryExport,
      })
    }
  }
  return {
    path: outputPath,
    code: `${lines.join('\n')}\n`,
    namespaceExport: surface.namespaceExport,
    linkageByOwner: links,
    sourceMappings: mappings,
    surface,
  }
}

function directQuantityModuleFor(
  file: AST.TaoFile,
  outputPath: string,
  runtimeRoot: QuantityNativeModuleOptions['runtimeRoot'],
  surface: QuantityPublicationSurface,
  canonicalLeaves: QuantityCanonicalLeaves,
): QuantityNativeModuleOutput | undefined {
  const owners = surface.declarations.filter(row => row.declaration === row.owner).map(row => {
    const plan = NumericUnits.declarationPlan(row.owner)
    Assert.defined(plan, 'quantity direct surface has its validated unit plan')
    return plan
  })
  if (owners.length === 0) {
    return undefined
  }
  return QuantityNativeModule.emit({
    owners,
    outputPath,
    runtimeRoot,
    reservedNames: quantityReservedNames(file),
    surfaceDeclarations: surface.declarations.map(row => row.declaration),
    parentsByOwner: new Map(surface.declarations.flatMap(row => {
      if (row.parent === undefined || row.declaration !== row.owner) {
        return []
      }
      const parent = canonicalLeaves.get(row.parent)
      Assert.defined(parent, `quantity parent ${row.parent.name} has a canonical publication leaf`)
      const link = parent.linkageByOwner.get(row.parent)
      Assert.defined(link, `quantity parent ${row.parent.name} has canonical factory linkage`)
      return [[row.owner, { owner: row.parent, path: parent.path, factoryExport: link.factoryExport }] as const]
    })),
  })
}

function quantitySurfaceFor(file: AST.TaoFile): QuantityPublicationSurface | undefined {
  const resolved = AST.streamAllContents(file).filter(AST.isTypeDeclaration).flatMap(declaration => {
    if (Type.isAbstractDomain(Type.ofDefinition(declaration))) {
      return []
    }
    const owner = declaration.aliasTarget === undefined
      ? NumericUnits.declarationPlan(declaration)?.owner
      : Type.quantityOwner(Type.ofDefinition(declaration))
    return owner === undefined
      ? []
      : [{ declaration, owner, ...(declaration === owner ? { parent: quantityParentOwner(owner) } : {}) }]
  })
  if (resolved.length === 0) {
    return undefined
  }
  const allocated = QuantityNativeModule.planSurface({
    declarations: resolved.map(row => row.declaration),
    parentsByDeclaration: new Map(
      resolved.flatMap(row => row.parent === undefined ? [] : [[row.declaration, row.parent] as const]),
    ),
    reservedNames: quantityReservedNames(file),
  })
  const declarations = resolved.map(row => {
    const names = allocated.byDeclaration.get(row.declaration)
    Assert.defined(names, 'quantity declaration has its allocated surface')
    return { ...row, ...names }
  })
  return {
    namespaceExport: allocated.namespaceExport,
    facadeNamespaceExport: allocated.namespaceExport,
    declarations,
    typeExportsByName: quantityNamedTypeExports(file, declarations),
  }
}

function quantityParentOwner(owner: AST.TypeDeclaration): AST.TypeDeclaration | undefined {
  const type = owner.type
  if (!type) {
    return undefined
  }
  const referenceTarget = AST.isDerivedTypeExpression(type)
    ? type.slots.unitBlocks.length > 0 || !AST.isNamedTypeReference(type.base)
      ? undefined
      : Type.definitionOfReference(type.base)
    : AST.isNamedTypeReference(type)
    ? Type.definitionOfReference(type)
    : undefined
  if (!AST.isTypeDeclaration(referenceTarget)) {
    return undefined
  }
  const visited = new Set<AST.TypeDeclaration>()
  let parent = referenceTarget
  while (parent.aliasTarget !== undefined) {
    Assert(!visited.has(parent), `quantity parent alias chain for ${owner.name} is acyclic`)
    visited.add(parent)
    const target = parent.aliasTarget.member.ref
    Assert(AST.isTypeDeclaration(target), `quantity parent alias ${parent.name} resolves to a type declaration`)
    parent = target
  }
  return Type.isAbstractDomain(Type.ofDefinition(parent)) || NumericUnits.declarationPlan(parent) === undefined
    ? undefined
    : parent
}

function canonicalQuantityLink(owner: AST.TypeDeclaration, leaves: QuantityCanonicalLeaves): {
  leaf: QuantityCanonicalLeaf
  link: QuantityNativeLinkage
} {
  const candidates = [...leaves].filter(([candidate]) =>
    physicalQuantityOwnerKey(candidate) === physicalQuantityOwnerKey(owner)
  )
  Assert(candidates.length === 1, 'quantity forwarding has one validated canonical owner leaf')
  const [canonical, leaf] = candidates[0]!
  const current = NumericUnits.declarationPlan(owner)
  const validated = NumericUnits.declarationPlan(canonical)
  Assert(
    current !== undefined && validated !== undefined
      && JSON.stringify([current.units, current.defaultUnit])
        === JSON.stringify([validated.units, validated.defaultUnit]),
    'quantity owner references match the validated canonical unit plan',
  )
  const link = leaf.linkageByOwner.get(canonical)
  Assert.defined(link, 'canonical quantity leaf retains its owner linkage')
  return { leaf, link }
}

function physicalQuantityOwnerKey(owner: AST.TypeDeclaration): string {
  Assert.defined(owner.$cstNode, 'canonical quantity owner has source coordinates')
  return JSON.stringify([
    FS.resolvePath(AST.getDocument(owner).uri.path),
    owner.$cstNode.offset,
    owner.$type,
    owner.name,
  ])
}

function quantityReferencedOwnersOf(file: AST.TaoFile): readonly AST.TypeDeclaration[] {
  const owners = new Set<AST.TypeDeclaration>()
  const addOwnerAndParents = (owner: AST.TypeDeclaration): void => {
    if (
      owners.has(owner) || Type.isAbstractDomain(Type.ofDefinition(owner))
      || NumericUnits.declarationPlan(owner) === undefined
    ) {
      return
    }
    owners.add(owner)
    const parent = quantityParentOwner(owner)
    if (parent !== undefined) {
      addOwnerAndParents(parent)
    }
  }
  const addType = (type: ASTUtils.TaoType): void => {
    const owner = Type.quantityOwner(type)
    if (owner !== undefined) {
      addOwnerAndParents(owner)
    }
  }
  for (const node of AST.streamAllContents(file)) {
    if (AST.isTypeDefinition(node)) {
      addType(Type.ofDefinition(node))
    } else if (AST.isTypeReference(node)) {
      addType(Type.ofReference(node))
    } else if (AST.isValueDeclaration(node)) {
      addType(Type.ofValueDeclaration(node))
    }
    if (AST.isNumericUnitConstruction(node)) {
      const resolved = NumericUnits.resolveSuffix(node)
      if (resolved !== undefined) {
        addOwnerAndParents(resolved.plan.owner)
      }
    }
    for (const reference of AST.streamReferences(node)) {
      const target = 'ref' in reference.reference ? reference.reference.ref : undefined
      if (AST.isTypeDefinition(target)) {
        addType(Type.ofDefinition(target))
      } else if (AST.isValueDeclaration(target)) {
        addType(Type.ofValueDeclaration(target))
      }
    }
  }
  return [...owners]
}

function quantityReservedNames(file: AST.TaoFile): string[] {
  const contracts = contractsOf(file, file.statements, true)
  return [
    'TR',
    ...contracts.map(contract => contract.exportName),
    ...contracts.map((_, index) => contractTypeName(contracts, index)),
    ...file.statements.filter(isRuntimeConfigurableDeclaration).map(declaration => `${declaration.name}Config`),
    ...AST.streamAllContents(file).flatMap(node => 'name' in node && typeof node.name === 'string' ? [node.name] : []),
  ]
}

function relativeModulePath(from: string, to: string): string {
  const relative = FS.relativePath(FS.dirname(from), to).replace(/\.ts$/, '')
  return relative.startsWith('./') || relative.startsWith('../') ? relative : `./${relative}`
}

function quantityExportsFor(_file: AST.TaoFile, modulePath: string, leaf: QuantityPublicationModule): string {
  const specifier = JSON.stringify(relativeModulePath(modulePath, leaf.path))
  const namedTypes = leaf.surface.typeExportsByName
  return [
    `export { ${leaf.namespaceExport} } from ${specifier}`,
    ...leaf.surface.declarations.flatMap(link => [
      `export { ${link.factoryExport} } from ${specifier}`,
      `export type { ${link.valueTypeExport} } from ${specifier}`,
      ...namedTypes.has(link.typeMember)
        ? [`export type { ${link.valueTypeExport} as ${link.typeMember} } from ${specifier}`]
        : [],
    ]),
  ].join('\n')
}

function quantityNamedTypeExports(
  file: AST.TaoFile,
  declarations: readonly QuantityPublicationDeclaration[],
): ReadonlyMap<string, string> {
  const contracts = contractsOf(file, file.statements, true)
  const reserved = new Set([
    ...contracts.map(contract => contract.exportName),
    ...contracts.map((_, index) => contractTypeName(contracts, index)),
    ...file.statements.filter(isRuntimeConfigurableDeclaration).map(declaration => `${declaration.name}Config`),
    ...file.statements.filter(AST.isTypeDeclaration).filter(declaration =>
      AST.isCaseSetTypeExpression(declaration.type)
    )
      .map(declaration => declaration.name),
  ])
  return new Map(
    declarations.filter(link => !reserved.has(link.typeMember))
      .map(link => [link.typeMember, link.valueTypeExport]),
  )
}

function bridgeOutputPath(projectRoot: string, sourcePath: string, origin?: ModuleOrigin): string {
  if (isForeignOrigin(origin, projectRoot)) {
    return `${dependencySnapshotPath(projectRoot, sourcePath, origin)}.ts`
  }
  if (FS.pathIsWithin(sourcePath, projectRoot)) {
    return FS.resolvePath(`.tao-ts/${FS.relativePath(projectRoot, sourcePath)}.ts`, projectRoot)
  }
  return `${
    dependencySnapshotPath(
      projectRoot,
      sourcePath,
      origin ?? {
        projectRoot: FS.dirname(sourcePath),
        modulePath: FS.dirname(sourcePath),
      },
    )
  }.ts`
}

function isForeignOrigin(origin: ModuleOrigin | undefined, projectRoot: string): origin is ModuleOrigin {
  return origin !== undefined && FS.resolvePath(origin.projectRoot) !== FS.resolvePath(projectRoot)
}

/** Place every file from one selected dependency origin in a private requester-owned snapshot. */
function dependencySnapshotPath(projectRoot: string, sourcePath: string, origin: ModuleOrigin): string {
  const relative = FS.relativePath(origin.projectRoot, sourcePath)
  Assert(!relative.startsWith('..'), 'dependency origin contains its source', { origin, sourcePath })
  return FS.resolvePath(`.tao-ts/.dependencies/${dependencyNamespace(origin.projectRoot)}/${relative}`, projectRoot)
}

/** One physical dependency project has one private source and npm-resolution environment. */
function dependencyNamespace(originProjectRoot: string): string {
  return Platform.sha256Hex(FS.resolvePath(originProjectRoot))
}

function contractsOf(
  file: AST.TaoFile,
  statements: readonly AST.Statement[] = file.statements,
  namesOnly = false,
): BridgeContract[] {
  const contracts: BridgeContract[] = []
  const nodes = statements.flatMap(statement => [statement, ...AST.streamAllContents(statement)])
  for (const bridge of nodes.filter(AST.isFromExpression)) {
    const expression = bridge.expression
    const exportName = AST.isFunctionCallExpression(expression)
      ? expression.function.$refText
      : AST.isValueReference(expression)
      ? expression.target.$refText
      : undefined
    if (exportName === undefined) {
      continue
    }
    const contextual = AST.getDocument(bridge).uri.path.endsWith('/@tao/auth/Auth.tao')
    if (contextual && exportName === 'Session') {
      contracts.push({
        exportName,
        path: bridge.path,
        sourceRange: bridgeOwnerRange(bridge),
        arity: '2',
        result: 'TR.Evaluable',
        type: '(scope: TR.AuthScope, cases: Readonly<Record<string, TR.Evaluable>>) => TR.Evaluable',
      })
      continue
    }
    const result = bridgedResultType(bridge)
    if (result === undefined) {
      continue
    }
    const type = namesOnly ? '' : AST.isFunctionCallExpression(expression)
      ? `(${contextual ? 'scope: TR.AuthScope, ' : ''}${
        expression.argumentList?.arguments.map((argument, index) =>
          `arg${index}: ${foreignActionParameterType(Type.ofArgument(argument))}`
        ).join(', ') ?? ''
      }) => ${typescriptType(result)}`
      : result.kind === 'primitive' && result.primitive === 'action'
      ? `(${
        result.parameters.map((parameter, index) =>
          `arg${index}${parameter.optional ? '?' : ''}: ${foreignActionParameterType(parameter.type)}`
        ).join(', ')
      }) => void | Promise<void>`
      : typescriptType(result)
    const actionValue = result.kind === 'primitive' && result.primitive === 'action'
    contracts.push({
      ...(AST.isFunctionCallExpression(expression)
        ? { arity: String((expression.argumentList?.arguments.length ?? 0) + (contextual ? 1 : 0)) }
        : actionValue
        ? { arity: String(result.parameters.length), result: 'void | Promise<void>' }
        : {}),
      exportName,
      path: bridge.path,
      sourceRange: bridgeOwnerRange(bridge),
      type,
    })
  }
  for (const action of nodes.filter(AST.isActionDeclaration)) {
    if (action.foreign === undefined) {
      continue
    }
    if (authLibraryExport(action)) {
      contracts.push({
        arity: '1',
        exportName: action.name,
        path: action.foreign.path,
        sourceRange: action.$cstNode?.range,
        result: 'TR.Action<[]>',
        type: '(scope: TR.AuthScope) => TR.Action<[]>',
      })
      continue
    }
    // The compiler fills Tao defaults before invoking the handwritten implementation.
    const parameters = namesOnly
      ? []
      : AST.parametersOf(action).map((parameter, index) =>
        `arg${index}: ${foreignActionParameterType(Type.ofParameter(parameter))}`
      )
    const result = namesOnly ? '' : action.returnType ? typescriptType(Type.ofActionResult(action)) : 'void'
    contracts.push({
      arity: String(parameters.length),
      exportName: action.name,
      path: action.foreign.path,
      sourceRange: action.$cstNode?.range,
      result: `${result} | Promise<${result}>`,
      type: `(${parameters.join(', ')}) => ${result} | Promise<${result}>`,
    })
  }
  for (const view of nodes.filter(AST.isViewDeclaration)) {
    const foreign = view.foreign
    if (foreign === undefined) {
      continue
    }
    // Tao fills defaults before passing props to the handwritten component.
    const parameters = namesOnly ? [] : AST.parametersOf(view).map(parameter => {
      const value = viewParameterType(Type.ofParameter(parameter))
      return `${JSON.stringify(Type.parameterName(parameter))}: ${
        parameter.mutable
          ? `{ value: ${value}; change: (next: ${value}) => void | Promise<void> }`
          : value
      }`
    })
    const slots = foreign.slots.length === 0
      ? []
      : [`Slots: { ${foreign.slots.map(slot => `${JSON.stringify(slot.name)}: any`).join('; ')} }`]
    const children = foreign.content === 'content' ? ['children?: any'] : []
    const authProps = authLibraryExport(view)
      ? ['Auth?: TR.AuthScope', ...(view.name === 'AccountView' ? ['Account?: TR.Evaluable'] : [])]
      : []
    const props = [...parameters, ...authProps, 'Layout: any', 'Tag: any', ...slots, ...children]
    contracts.push({
      exportName: view.name,
      path: foreign.path,
      sourceRange: view.$cstNode?.range,
      type: `(props: { ${props.join('; ')} }) => ReturnType<typeof TR.VisualNativeRoot>`,
    })
  }
  for (const declaration of statements.filter(AST.isConfigurableDeclaration)) {
    const primitive = AST.configurationPrimitiveOf(declaration)
    if (primitive !== 'nav' && primitive !== 'datasource' && primitive !== 'auth') {
      continue
    }
    const implementation = directConfigurationImplementation(declaration)
    if (implementation === undefined) {
      continue
    }
    contracts.push({
      arity: '0',
      exportName: implementation.exportName,
      path: implementation.path,
      sourceRange: declaration.$cstNode?.range,
      type: `() => ${
        primitive === 'nav' ? 'TR.NavKind' : primitive === 'auth' ? 'TR.AuthProvider' : 'TR.DataProvider'
      }`,
    })
  }
  return contracts
}

function directConfigurationImplementation(
  declaration: AST.ConfigurableDeclaration,
): AST.ConfigurationImplementation | undefined {
  if (declaration.aliasTarget !== undefined) {
    return undefined
  }
  const implementation = AST.configurationImplementationOf(declaration)
  let owner: AST.Node | undefined = implementation
  while (owner !== undefined && owner !== declaration) {
    owner = owner.$container
  }
  return owner === declaration && implementation?.path !== undefined ? implementation : undefined
}

function bridgeOwnerRange(bridge: AST.FromExpression): DiagnosticRange | undefined {
  const owner = bridge.$container
  if (AST.isReturnStatement(owner)) {
    return nativeReturnOwner(owner)?.$cstNode?.range ?? bridge.$cstNode?.range
  }
  return owner?.$cstNode?.range ?? bridge.$cstNode?.range
}

function bridgedResultType(bridge: AST.FromExpression): ASTUtils.TaoType | undefined {
  const owner = bridge.$container
  if (AST.isReturnStatement(owner)) {
    const callable = nativeReturnOwner(owner)
    if (AST.isAssociatedConverterDeclaration(callable)) {
      return Type.associatedConverterDescriptor(callable)?.result
    }
    return callable?.returnType === undefined ? undefined : Type.ofFunctionReturn(callable)
  }
  if (AST.isAliasDeclaration(owner)) {
    return owner.type === undefined ? undefined : Type.ofReference(owner.type)
  }
  if (AST.isTypeProperty(owner)) {
    return owner.type === undefined ? undefined : Type.ofReference(owner.type)
  }
  return undefined
}

/** The nearest real callable supplies the native return contract, including converter targets. */
function nativeReturnOwner(
  statement: AST.ReturnStatement,
): AST.FunctionDeclaration | AST.AssociatedFunctionDeclaration | AST.AssociatedConverterDeclaration | undefined {
  let node: AST.Node | undefined = statement.$container
  while (node !== undefined) {
    if (
      AST.isFunctionDeclaration(node) || AST.isAssociatedFunctionDeclaration(node)
      || AST.isAssociatedConverterDeclaration(node)
    ) {
      return node
    }
    node = node.$container
  }
  return undefined
}

function typescriptType(type: ASTUtils.TaoType, seen = new Set<AST.EntityDataDeclaration>()): string {
  if (type.kind === 'primitive' && type.primitive === 'numeric' && Type.isAbstractDomain(type)) {
    return 'TR.Value<TR.QuantityPayload>'
  }
  const owner = Type.quantityOwner(type)
  if (owner !== undefined) {
    const binding = quantityTypeBindings.get(owner)
    Assert.defined(binding, 'native quantity type has an exact owner binding')
    return binding
  }
  return Switch.kind(type, {
    capability: () => 'TR.Capability',
    primitive: type => {
      if (type.primitive === 'action') {
        return runtimeActionType(type)
      }
      if (type.primitive === 'text' || type.primitive === 'color' || type.primitive === 'shortcut') {
        return 'string'
      }
      if (
        type.primitive === 'number' || type.primitive === 'numeric' || type.primitive === 'time'
        || type.primitive === 'duration'
      ) {
        return 'number'
      }
      if (type.primitive === 'boolean') {
        return 'boolean'
      }
      if (type.primitive === 'none') {
        return 'null'
      }
      if (type.primitive === 'rendered') {
        return 'TR.Rendered'
      }
      return 'unknown'
    },
    list: type => `Array<${typescriptType(type.element ?? { kind: 'unresolved' }, seen)}>`,
    union: type => type.members.map(member => typescriptType(member, seen)).join(' | '),
    entity: type => {
      if (seen.has(type.entity)) {
        return 'unknown'
      }
      seen.add(type.entity)
      const fields = Type.dataFields(type.entity).map(field =>
        `${JSON.stringify(field.name)}${field.optional ? '?' : ''}: ${typescriptType(Type.dataFieldType(field), seen)}${
          field.optional ? ' | null' : ''
        }`
      )
      seen.delete(type.entity)
      return `{ ${fields.join('; ')} }`
    },
    item: type => {
      const fields = (type.item ? Type.itemFields(type.item) : []).map(field => {
        const required = Type.itemFieldRequiresValue(field)
        const fieldType = Type.itemFieldType(field)
        const outputType = fieldType.kind === 'primitive' && fieldType.primitive === 'action'
          ? itemActionType(fieldType)
          : typescriptType(fieldType, seen)
        return `${JSON.stringify(field.name)}${required ? '' : '?'}: ${outputType}${required ? '' : ' | null'}`
      })
      return `{ ${fields.join('; ')} }`
    },
    enum: () => 'any',
    unresolved: () => 'unknown',
  })
}

/** View action parameters retain the runtime's invokable action and reactive argument wrappers. */
function viewParameterType(type: ASTUtils.TaoType): string {
  if (type.kind === 'capability') {
    return typescriptType(type)
  }
  if (type.kind === 'primitive' && type.primitive === 'action') {
    return runtimeActionType(type)
  }
  return typescriptType(type)
}

function foreignActionParameterType(type: ASTUtils.TaoType): string {
  return type.kind === 'primitive' && type.primitive === 'action' ? runtimeActionType(type) : typescriptType(type)
}

function runtimeActionType(type: Extract<ASTUtils.TaoType, { kind: 'primitive'; primitive: 'action' }>): string {
  const parameters = type.parameters.map(parameter =>
    `${runtimeActionArgumentType(parameter.type)}${parameter.optional ? '?' : ''}`
  )
  return `TR.ActionValue<[${parameters.join(', ')}]>`
}

function runtimeActionArgumentType(type: ASTUtils.TaoType): string {
  if (type.kind === 'capability') {
    return typescriptType(type)
  }
  if (Type.quantityOwner(type) !== undefined) {
    return typescriptType(type)
  }
  if (type.kind === 'primitive' && type.primitive === 'action') {
    return `TR.Action<[${
      type.parameters.map(parameter => `${runtimeActionArgumentType(parameter.type)}${parameter.optional ? '?' : ''}`)
        .join(', ')
    }]>`
  }
  return type.kind === 'union' ? 'TR.Evaluable' : `TR.Value<${typescriptType(type)}>`
}

function itemActionType(type: Extract<ASTUtils.TaoType, { kind: 'primitive'; primitive: 'action' }>): string {
  return `{ invoke(...args: [${
    type.parameters.map(parameter =>
      Type.quantityOwner(parameter.type) !== undefined
        ? typescriptType(parameter.type)
        : `TR.Value<${typescriptType(parameter.type)}>`
    ).join(', ')
  }]): void | Promise<void> }`
}

/**
 * runtimeTypeImport names `TR` by a path from the generated module. The module is often opened
 * outside the project that maps `@tao/runtime`, so a package specifier does not resolve there.
 */
function runtimeTypeImport(modulePath: string, runtimeRoot?: string): string {
  const runtime = runtimeRoot === undefined
    ? TaoResources.resolve(`${TaoResources.RUNTIME_DIRECTORY}/TaoRuntime-src/TR.ts`)
      ?? FS.resolvePath('../../apps/runtime/TaoRuntime-src/TR.ts', import.meta.dirname)
    : FS.resolvePath('TaoRuntime-src/TR.ts', runtimeRoot)
  const relative = FS.relativePath(FS.dirname(FS.resolvePath(modulePath)), runtime).replace(/\.ts$/, '')
  const specifier = relative.startsWith('.') ? relative : `./${relative}`
  return `import type TR from ${JSON.stringify(specifier)}`
}

function moduleFor(
  contracts: readonly BridgeContract[],
  typeStatements: readonly AST.Statement[],
  modulePath: string,
  sourcePath: string,
  implementationPaths: readonly { sourcePath: string; path: string }[],
  runtimeRoot?: string,
  quantityModule?: QuantityPublicationModule,
  file?: AST.TaoFile,
): { code: string; sourceMappings: readonly BridgeSourceMapping[] } {
  const imports = new Map<string, string>()
  const lines = [bridgeGeneratedMarker, '']
  if (quantityModule !== undefined) {
    Assert.defined(file, 'quantity companion has its source AST')
    lines.push(quantityExportsFor(file, modulePath, quantityModule), '')
  }
  const sourceMappings: BridgeSourceMapping[] = []
  const sourceComment = (range: DiagnosticRange | undefined): void => {
    if (range === undefined) {
      return
    }
    const relative = FS.relativePath(FS.dirname(modulePath), sourcePath)
    lines.push(`// Source: ${relative}:${range.start.line + 1}:${range.start.character + 1}`)
  }
  const mapLine = (range: DiagnosticRange | undefined): void => {
    if (range === undefined) {
      return
    }
    const line = lines.length - 1
    const content = lines[line] ?? ''
    sourceMappings.push({
      generated: { start: { line, character: 0 }, end: { line, character: content.length } },
      source: range,
    })
  }
  const configurationTypes = typeStatements.filter(isRuntimeConfigurableDeclaration)
    .map(declaration => ({ code: sourceConfigurationType(declaration), sourceRange: declaration.$cstNode?.range }))
  const caseSets = typeStatements.filter(AST.isTypeDeclaration).filter(declaration =>
    AST.isCaseSetTypeExpression(declaration.type)
  )
  const reservedNames = new Set([
    'TR',
    ...quantityModule === undefined
      ? []
      : [
        quantityModule.namespaceExport,
        ...quantityModule.surface.typeExportsByName.keys(),
        ...quantityModule.surface.declarations.flatMap(row => [row.valueTypeExport, row.factoryExport]),
      ],
    ...contracts.map((_, index) => contractTypeName(contracts, index)),
    ...typeStatements.filter(isRuntimeConfigurableDeclaration).map(declaration => `${declaration.name}Config`),
    ...caseSets.map(declaration => declaration.name),
  ])
  const reserveName = (base: string): string => {
    let name = base
    for (let suffix = 1; reservedNames.has(name); suffix++) {
      name = `${base}_${suffix}`
    }
    reservedNames.add(name)
    return name
  }
  if (
    contracts.some(contract => contract.type.includes('TR.'))
    || caseSets.length > 0
    || contracts.some(contract => contract.type.includes('TR.NavKind') || contract.type.includes('TR.DataProvider'))
    || contracts.some(contract => contract.type.includes('TR.VisualNativeRoot'))
    || configurationTypes.some(type => type.code.includes('TR.'))
  ) {
    lines.push(runtimeTypeImport(modulePath, runtimeRoot))
  }
  for (const contract of contracts) {
    if (!imports.has(contract.path)) {
      imports.set(contract.path, `Sidecar${imports.size + 1}`)
    }
  }
  if (imports.size === 1) {
    const onlyPath = [...imports.keys()][0]
    Assert.defined(onlyPath, 'single bridge sidecar has one path')
    imports.set(onlyPath, 'Sidecar')
  }
  for (const [path, plannedName] of imports) {
    const name = reserveName(plannedName)
    imports.set(path, name)
    const sidecar = FS.resolvePath(path, FS.dirname(sourcePath))
    const implementation = implementationPaths.find(item => item.sourcePath === sidecar)?.path ?? sidecar
    const relative = FS.relativePath(FS.dirname(modulePath), implementation).replace(/\.tsx?$/, '')
    lines.push(`import type * as ${name} from ${JSON.stringify(relative.startsWith('.') ? relative : `./${relative}`)}`)
  }
  lines.push('')
  const checkName = reserveName('__TaoBridgeCheck')
  if (contracts.length > 0) {
    // Exported type aliases remain erased and valid under noUnusedLocals.
    lines.push(`export type ${checkName}<Expected, Actual extends Expected> = Actual`, '')
  }
  for (const declaration of caseSets) {
    sourceComment(declaration.$cstNode?.range)
    lines.push(caseSetTypeDeclaration(declaration))
    mapLine(declaration.$cstNode?.range)
  }
  if (caseSets.length > 0) {
    lines.push('')
  }
  for (const [index, contract] of contracts.entries()) {
    const typeName = contractTypeName(contracts, index)
    const sidecar = imports.get(contract.path)
    Assert.defined(sidecar, 'bridge sidecar import is planned')
    sourceComment(contract.sourceRange)
    lines.push(`export type ${typeName} = ${contract.type}`)
    mapLine(contract.sourceRange)
    lines.push(
      `export type ${
        reserveName(`__TaoBridgeSignature${index + 1}`)
      } = ${checkName}<${typeName}, typeof ${sidecar}.${contract.exportName}>`,
    )
    mapLine(contract.sourceRange)
    if (contract.arity !== undefined) {
      lines.push(
        `export type ${
          reserveName(`__TaoBridgeArity${index + 1}`)
        } = ${checkName}<Parameters<typeof ${sidecar}.${contract.exportName}>['length'], ${contract.arity}>`,
      )
      mapLine(contract.sourceRange)
    }
    if (contract.result !== undefined) {
      lines.push(
        `export type ${
          reserveName(`__TaoBridgeResult${index + 1}`)
        } = ${checkName}<${contract.result}, ReturnType<typeof ${sidecar}.${contract.exportName}>>`,
      )
      mapLine(contract.sourceRange)
    }
    lines.push('')
  }
  for (const type of configurationTypes) {
    sourceComment(type.sourceRange)
    for (const line of type.code.split('\n')) {
      lines.push(line)
      mapLine(type.sourceRange)
    }
    lines.push('')
  }
  return { code: `${lines.join('\n').trimEnd()}\n`, sourceMappings }
}

function caseSetTypeDeclaration(declaration: AST.TypeDeclaration): string {
  const cases = AST.caseSetCasesOf(declaration).map(item => JSON.stringify(AST.caseSetCaseName(item)))
  return `export declare const ${declaration.name}: Readonly<Record<${cases.join(' | ')}, TR.Value<any>>>`
}

/** Source metadata expands transparent aliases so their type needs no generated target module. */
function sourceConfigurationType(declaration: AST.ConfigurableDeclaration): string {
  let source = declaration
  const visited = new Set<AST.ConfigurableDeclaration>()
  while (AST.isTypeDeclaration(source) && source.aliasTarget !== undefined) {
    Assert(!visited.has(source), `acyclic configuration alias ${declaration.name}`)
    visited.add(source)
    const target = source.aliasTarget.member.ref
    Assert(
      target !== undefined && isRuntimeConfigurableDeclaration(target),
      `resolved configuration alias ${declaration.name}`,
    )
    source = target
  }
  const definition = Langium.toString(ConfigurationCompiler.ConfigurationType(source)).trimEnd()
  return definition.replace(/^export type \S+Config\b/, `export type ${declaration.name}Config`)
}

function contractTypeName(contracts: readonly BridgeContract[], index: number): string {
  const contract = contracts[index]
  Assert.defined(contract, 'bridge contract index is planned')
  return contracts.filter(candidate => candidate.exportName === contract.exportName).length === 1
    ? contract.exportName
    : `Bridge${index + 1}_${contract.exportName}`
}
